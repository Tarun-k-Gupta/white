#!/usr/bin/env bash
# One-command offline stack: anvil + contracts + MOCK 0G + core + robot adapter.
# No keys, no funds, no network. Uses anvil's public test keys (never use them anywhere else).
# For the real thing (Galileo + 0G Router + 0G Storage) see README "Run on 0G testnet".
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FOUNDRY="${FOUNDRY_BIN:-$HOME/.foundry/bin}"
LOGS="$ROOT/.dev-logs"
mkdir -p "$LOGS"
RPC=http://127.0.0.1:8545
# anvil default accounts #0 (operator/deployer) and #1 (robot) - public test keys
K0=0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80
K1=0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d

pids=()
cleanup() { for p in "${pids[@]:-}"; do kill "$p" 2>/dev/null || true; done; }
trap cleanup EXIT INT TERM

if ! curl -s -X POST -H 'content-type: application/json' --data '{"jsonrpc":"2.0","id":1,"method":"eth_chainId","params":[]}' $RPC >/dev/null 2>&1; then
  "$FOUNDRY/anvil" --silent --port 8545 >"$LOGS/anvil.log" 2>&1 &
  pids+=($!)
  for _ in $(seq 1 50); do curl -s $RPC -X POST -H 'content-type: application/json' --data '{"jsonrpc":"2.0","id":1,"method":"eth_chainId","params":[]}' >/dev/null 2>&1 && break; sleep 0.2; done
fi

echo "› deploying contracts to anvil"
(cd "$ROOT/contracts" && DEPLOYER_PRIVATE_KEY=$K0 "$FOUNDRY/forge" script script/Deploy.s.sol --rpc-url $RPC --broadcast --silent >"$LOGS/deploy.log" 2>&1)
REG=$(node -e "console.log(require('$ROOT/contracts/deployments/31337.json').blackboxRegistry)")
ROB=$(node -e "console.log(require('$ROOT/contracts/deployments/31337.json').robotRegistry)")

cat >"$ROOT/.env.local" <<EOF
# generated by scripts/dev-local.sh - local anvil + MOCK 0G (not 0G!)
CHAIN=local
BLACKBOX_REGISTRY=$REG
ROBOT_REGISTRY=$ROB
OPERATOR_PRIVATE_KEY=$K0
ROBOT_PRIVATE_KEY=$K1
ROBOT_NAME=blackbox-drone-local
STORAGE=local
ZG_MODE=mock
LEASE_MS=${LEASE_MS:-6000}
SIM_SPEED=${SIM_SPEED:-1.5}
EOF
export BLACKBOX_ENV=.env.local
echo "› registering robot on SimpleRobotRegistry"
ROBOT_ID=$(cd "$ROOT/core" && npx tsx scripts/setup-robot.ts | sed -n 's/^ROBOT_ID=//p')
echo "ROBOT_ID=$ROBOT_ID" >>"$ROOT/.env.local"

echo "› starting mock 0G, core, robot (logs in .dev-logs/)"
(cd "$ROOT/core" && npx tsx src/mock0g/server.ts >"$LOGS/mock0g.log" 2>&1) & pids+=($!)
(cd "$ROOT/core" && npx tsx src/server.ts >"$LOGS/core.log" 2>&1) & pids+=($!)
(cd "$ROOT/robot" && ./.venv/bin/python -m blackbox_robot.adapter >"$LOGS/robot.log" 2>&1) & pids+=($!)
for _ in $(seq 1 60); do curl -s http://127.0.0.1:8787/api/config >/dev/null 2>&1 && curl -s http://127.0.0.1:8801/health >/dev/null 2>&1 && break; sleep 0.5; done

echo
echo "  Operator console  http://127.0.0.1:8787"
echo "  Public verifier   http://127.0.0.1:8787/verify.html"
echo "  BlackboxRegistry  $REG (anvil)"
echo "  Ctrl-C stops everything."
wait
